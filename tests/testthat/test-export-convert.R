test_that("export and conversion reject input aliases before any execution", {
  td <- tempfile("alder-output-alias-")
  dir.create(td)
  file_bytes <- function(path) readBin(path, "raw", n = file.info(path)$size)
  effect <- file.path(td, "export-ran")
  literal <- function(value) paste(utils::capture.output(dput(value)), collapse = "")
  export_input <- file.path(td, "export-input.R")
  writeLines(c(
    "# %%",
    paste0("writeLines('ran', ", literal(effect), ")")
  ), export_input, useBytes = TRUE)
  convert_inputs <- list(
    ipynb = file.path(td, "convert-input.ipynb"),
    rmd = file.path(td, "convert-input.Rmd"),
    qmd = file.path(td, "convert-input.qmd")
  )
  jsonlite::write_json(list(
    cells = list(list(cell_type = "code", metadata = list(),
                      source = I(c("x <- 1\n")), outputs = list(),
                      execution_count = NULL)),
    metadata = list(), nbformat = 4L, nbformat_minor = 5L
  ), convert_inputs$ipynb, auto_unbox = TRUE, pretty = TRUE, null = "null")
  writeLines(c("# Conversion input", "", "```{r}", "x <- 1", "```"),
             convert_inputs$rmd, useBytes = TRUE)
  writeLines(c("# Conversion input", "", "```{r}", "x <- 1", "```"),
             convert_inputs$qmd, useBytes = TRUE)
  export_original <- file_bytes(export_input)
  convert_originals <- lapply(convert_inputs, file_bytes)

  check_rejected <- function(expr, code) {
    err <- tryCatch(force(expr), error = identity)
    expect_s3_class(err, "alder_error")
    expect_identical(err$code, code)
    expect_identical(conditionMessage(err), "output path must not refer to input file")
  }

  for (format in alder:::export_formats) {
    check_rejected(alder:::alder_export(export_input, format, out = export_input),
                   "export_failed")
    expect_identical(file_bytes(export_input), export_original)
  }
  check_rejected(alder:::alder_export(
    export_input, "script",
    out = file.path(dirname(export_input), ".", basename(export_input))
  ), "export_failed")
  expect_identical(file_bytes(export_input), export_original)
  expect_false(file.exists(effect))
  for (i in seq_along(convert_inputs)) {
    convert_input <- convert_inputs[[i]]
    check_rejected(alder:::alder_convert(convert_input, out = convert_input),
                   "convert_failed")
    expect_identical(file_bytes(convert_input), convert_originals[[i]])
  }
  check_rejected(alder:::alder_convert(
    convert_inputs$qmd,
    out = file.path(dirname(convert_inputs$qmd), ".", basename(convert_inputs$qmd))
  ), "convert_failed")
  expect_identical(file_bytes(convert_inputs$qmd), convert_originals$qmd)

  export_symlink <- file.path(td, "export-symlink.R")
  if (isTRUE(file.symlink(export_input, export_symlink))) {
    check_rejected(alder:::alder_export(export_input, "script", out = export_symlink),
                   "export_failed")
    expect_identical(file_bytes(export_input), export_original)
  }
  convert_symlink <- file.path(td, "convert-symlink.qmd")
  if (isTRUE(file.symlink(convert_inputs$qmd, convert_symlink))) {
    check_rejected(alder:::alder_convert(convert_inputs$qmd, out = convert_symlink),
                   "convert_failed")
    expect_identical(file_bytes(convert_inputs$qmd), convert_originals$qmd)
  }

  export_hardlink <- file.path(td, "export-hardlink.R")
  if (isTRUE(file.link(export_input, export_hardlink))) {
    check_rejected(alder:::alder_export(export_input, "script", out = export_hardlink),
                   "export_failed")
    expect_identical(file_bytes(export_input), export_original)
  }
  convert_hardlink <- file.path(td, "convert-hardlink.qmd")
  if (isTRUE(file.link(convert_inputs$qmd, convert_hardlink))) {
    check_rejected(alder:::alder_convert(convert_inputs$qmd, out = convert_hardlink),
                   "convert_failed")
    expect_identical(file_bytes(convert_inputs$qmd), convert_originals$qmd)
  }
  expect_false(file.exists(effect))
})

