test_that("alder_test reports success and failure through subprocess status", {
  td <- tempfile("alder-test-subprocess-")
  dir.create(td)
  # R CMD check relocates tests outside the loaded package. Carry its actual
  # namespace path and dependency libraries into the vanilla child instead.
  package_path <- normalizePath(
    getNamespaceInfo(asNamespace("alder"), "path"), mustWork = TRUE
  )
  libraries <- file.path(td, "libraries.rds")
  saveRDS(.libPaths(), libraries)
  runner <- file.path(td, "run-tests.R")
  writeLines(c(
    "args <- commandArgs(trailingOnly = TRUE)",
    ".libPaths(readRDS(args[[2L]]))",
    "if (file.exists(file.path(args[[1L]], 'Meta', 'package.rds'))) {",
    "  library(alder, lib.loc = dirname(args[[1L]]))",
    "} else {",
    "  pkgload::load_all(args[[1L]], quiet = TRUE)",
    "}",
    "stopifnot(identical(",
    "  normalizePath(getNamespaceInfo(asNamespace('alder'), 'path')),",
    "  normalizePath(args[[1L]])",
    "))",
    "alder::alder_test(args[[3L]])"
  ), runner, useBytes = TRUE)
  good <- file.path(td, "good.R")
  bad <- file.path(td, "bad.R")
  writeLines(c("# %%", "#| test: true", "testthat::expect_identical(1L, 1L)"),
             good, useBytes = TRUE)
  writeLines(c("# %%", "#| test: true", "testthat::expect_identical(1L, 2L)"),
             bad, useBytes = TRUE)
  run <- function(path) processx::run(
    file.path(R.home("bin"), "Rscript"),
    c("--vanilla", runner, package_path, libraries, path),
    error_on_status = FALSE, echo = FALSE
  )

  success <- run(good)
  failure <- run(bad)
  expect_identical(success$status, 0L)
  expect_gt(failure$status, 0L)
  expect_match(paste(failure$stdout, failure$stderr),
               "Expected 1L to be identical to 2L", fixed = TRUE)
})

