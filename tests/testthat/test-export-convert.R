  writeLines(c("# %%", "#| test: true", "testthat::expect_true(TRUE)"),
             path, useBytes = TRUE)
  seed_name <- paste0(".Random", ".seed")
  had_seed <- exists(seed_name, envir = .GlobalEnv, inherits = FALSE)
  previous_seed <- if (had_seed) get(seed_name, envir = .GlobalEnv) else NULL
  on.exit({
    if (had_seed) assign(seed_name, previous_seed, envir = .GlobalEnv)
    else rm(list = seed_name, envir = .GlobalEnv)
  }, add = TRUE)
  set.seed(20260904L)
  expected <- runif(2L)
  set.seed(20260904L)
  alder:::alder_test(path)
  observed <- runif(2L)
  expect_identical(observed, expected)
})

