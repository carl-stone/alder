  literal <- function(value) paste(utils::capture.output(dput(value)), collapse = "")
  cases <- list(
    syntax = c("# %%", "if (", "# %%",
               paste0("writeLines('ran', ", literal(marker), ")")),
    duplicate = c(
      "# %%", "duplicated <- 1L", paste0("writeLines('ran', ", literal(marker), ")"),
      "# %%", "duplicated <- 2L"
    ),
    cycle = c(
      "# %%", "cycle_a <- cycle_b + 1L", paste0("writeLines('ran', ", literal(marker), ")"),
      "# %%", "cycle_b <- cycle_a + 1L"
    ),
    dynamic = c(
      "# %%", "target <- 'dynamic_name'", paste0(
        "assign(target, writeLines('ran', ", literal(marker), "))"
      )
    )
  )
  for (name in names(cases)) {
    source <- file.path(td, paste0(name, ".R"))
    writeLines(cases[[name]], source, useBytes = TRUE)
    for (format in alder:::export_formats) {
      destination <- file.path(td, paste0(name, "-", format, ".out"))
      sentinel <- charToRaw(paste0("preserve ", name, " ", format, "\n"))
      writeBin(sentinel, destination)
      err <- tryCatch(
        alder:::alder_export(source, format, out = destination,
                             include_code = TRUE),
        error = identity
      )
      expect_true(inherits(err, "alder_error"), info = paste(name, format))
      expect_identical(err$code, "export_failed")
      expect_match(conditionMessage(err), switch(
        name,
        syntax = "unexpected end of input",
        duplicate = "duplicate definition of duplicated",
        cycle = "dependency cycle",
        dynamic = "assign() requires"
      ), fixed = TRUE)
      expect_identical(readBin(destination, "raw", n = file.info(destination)$size),
                       sentinel)
      expect_false(file.exists(marker))
      expect_length(list.files(
        td, pattern = "^\\.alder-export", all.files = TRUE
      ), 0L)
    }
  }
})

test_that("Markdown sidecar changes can roll back without residue", {
  td <- tempfile("alder-markdown-sidecar-")
  dir.create(td)
  sidecar <- file.path(td, "report_files")
  dir.create(sidecar)
  writeLines("old", file.path(sidecar, "old.txt"), useBytes = TRUE)
  stage <- file.path(td, ".alder-export-files-stage")
  dir.create(stage)
  writeLines("new", file.path(stage, "new.txt"), useBytes = TRUE)

  transaction <- alder:::export_markdown_sidecar_commit(stage, sidecar)
  expect_true(file.exists(file.path(sidecar, "new.txt")))
  alder:::export_markdown_sidecar_rollback(transaction)
  expect_true(file.exists(file.path(sidecar, "old.txt")))
  expect_false(file.exists(file.path(sidecar, "new.txt")))
  expect_length(list.files(td, pattern = "^\\.alder-export-files-backup", all.files = TRUE), 0L)

  stage <- file.path(td, ".alder-export-files-stage-final")
  dir.create(stage)
  writeLines("new", file.path(stage, "new.txt"), useBytes = TRUE)
  transaction <- alder:::export_markdown_sidecar_commit(stage, sidecar)
  alder:::export_markdown_sidecar_finalize(transaction)
  expect_true(file.exists(file.path(sidecar, "new.txt")))
  expect_length(list.files(td, pattern = "^\\.alder-export-files-backup", all.files = TRUE), 0L)
})
